#!/usr/bin/env python3
"""Regenerate Source/EmbeddedMonoFonts.h from Source/Resources/fonts/JetBrainsMono-*.ttf.

Same format as Source/EmbeddedFonts.h (gzip-compressed byte arrays + _LEN
constants), decoded once by BoutiqueLookAndFeel::loadGzippedTypeface.
JetBrains Mono is the numeric/readout face (CPU, RAM, dB, value boxes).
License: SIL OFL 1.1 - Source/Resources/fonts/OFL-JetBrainsMono.txt

Run from the repo root:  python tools/make_mono_fonts.py
"""
import gzip
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[1]
FONTS = ROOT / "Source" / "Resources" / "fonts"
OUT = ROOT / "Source" / "EmbeddedMonoFonts.h"

SPEC = [
    ("JetBrainsMono-Regular.ttf", "JETBRAINS_MONO_REGULAR_GZ"),
    ("JetBrainsMono-Bold.ttf", "JETBRAINS_MONO_BOLD_GZ"),
]


def main() -> None:
    lines = [
        "#pragma once",
        "#include <cstddef>",
        "",
        "// Generated by tools/make_mono_fonts.py - do not edit by hand.",
        "// SIL Open Font License 1.1 embedded fonts:",
        "// - JetBrains Mono Regular & Bold (Copyright The JetBrains Mono Project Authors)",
        "//   License text: Source/Resources/fonts/OFL-JetBrainsMono.txt",
        "namespace Fanfare {",
        "namespace EmbeddedMonoFonts {",
        "",
    ]
    for fname, const in SPEC:
        raw = (FONTS / fname).read_bytes()
        if raw[:4] not in (b"\x00\x01\x00\x00", b"OTTO", b"true"):
            raise SystemExit("%s does not look like a TrueType/OpenType font" % fname)
        gz = gzip.compress(raw, 9, mtime=0)
        lines.append("static const unsigned char %s[] = {" % const)
        for i in range(0, len(gz), 24):
            lines.append("    " + ", ".join("0x%02x" % b for b in gz[i : i + 24]) + ",")
        lines.append("};")
        lines.append("static constexpr size_t %s_LEN = %d;" % (const, len(gz)))
        lines.append("")
    lines.append("} // namespace EmbeddedMonoFonts")
    lines.append("} // namespace Fanfare")
    OUT.write_text("\n".join(lines) + "\n", newline="\r\n")
    print("wrote %s (%d KB)" % (OUT, OUT.stat().st_size // 1024))


if __name__ == "__main__":
    main()
