import os
import re
import xml.sax.saxutils as saxutils

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUTPUT_HEADER = os.path.join(REPO_ROOT, "Source", "BundledAssetsData.h")
OUTPUT_WXS = os.path.join(REPO_ROOT, "installer", "BundledPresets.wxs")

FOLDERS = ["strips", "synth-presets", "fm-presets", "fm-sysex"]

def sanitize_id(name):
    clean = re.sub(r'[^a-zA-Z0-9_]', '_', name)
    if clean and clean[0].isdigit():
        clean = "_" + clean
    return clean

def main():
    entries = []
    file_bytes_list = []

    for folder in FOLDERS:
        folder_path = os.path.join(REPO_ROOT, folder)
        if not os.path.exists(folder_path):
            continue
        for root, dirs, files in os.walk(folder_path):
            dirs.sort()
            for f in sorted(files):
                abs_path = os.path.join(root, f)
                rel_path = os.path.relpath(abs_path, REPO_ROOT).replace("\\", "/")
                with open(abs_path, "rb") as fp:
                    data = fp.read()
                file_idx = len(entries)
                entries.append((rel_path, file_idx, len(data)))
                file_bytes_list.append(data)

    print(f"Embedding {len(entries)} files into {OUTPUT_HEADER}...")

    # 1. Generate C++ embedded data header
    with open(OUTPUT_HEADER, "w", encoding="utf-8") as out:
        out.write("// Auto-generated by tools/generate_bundled_assets.py - DO NOT EDIT\n")
        out.write("#pragma once\n\n")
        out.write("#include <JuceHeader.h>\n")
        out.write("#include <cstdint>\n")
        out.write("#include <cstddef>\n\n")
        out.write("namespace Fanfare {\n")
        out.write("namespace BundledData {\n\n")

        for rel_path, idx, size in entries:
            data = file_bytes_list[idx]
            out.write(f"// {rel_path} ({size} bytes)\n")
            out.write(f"static const uint8_t file_{idx}[] = {{\n")
            hex_lines = []
            for i in range(0, len(data), 16):
                chunk = data[i:i+16]
                hex_lines.append("    " + ", ".join(f"0x{b:02x}" for b in chunk))
            out.write(",\n".join(hex_lines))
            out.write("\n};\n\n")

        out.write("struct Entry {\n")
        out.write("    const char* relativePath;\n")
        out.write("    const uint8_t* data;\n")
        out.write("    size_t size;\n")
        out.write("};\n\n")

        out.write(f"static const Entry kFiles[{len(entries)}] = {{\n")
        for rel_path, idx, size in entries:
            out.write(f'    {{ "{rel_path}", file_{idx}, {size} }},\n')
        out.write("};\n\n")

        out.write("} // namespace BundledData\n\n")

        out.write("void seedEmbeddedAssets(const juce::File& appRoot) {\n")
        out.write("    for (const auto& entry : BundledData::kFiles) {\n")
        out.write("        juce::File dest = appRoot.getChildFile(entry.relativePath);\n")
        out.write("        if (!dest.existsAsFile()) {\n")
        out.write("            dest.getParentDirectory().createDirectory();\n")
        out.write("            dest.replaceWithData(entry.data, entry.size);\n")
        out.write("        }\n")
        out.write("    }\n")
        out.write("}\n\n")
        out.write("} // namespace Fanfare\n")

    print(f"Generated {OUTPUT_HEADER} successfully ({os.path.getsize(OUTPUT_HEADER)} bytes).")

    # 2. Generate WiX ComponentGroup for MSI installer
    # Build a directory tree
    dir_tree = {} # dir_rel_path -> { 'subdirs': set(), 'files': list of (filename, full_rel_path, idx) }
    dir_tree[""] = {'subdirs': set(), 'files': []}

    for rel_path, idx, size in entries:
        parts = rel_path.split("/")
        dir_parts = parts[:-1]
        fname = parts[-1]
        cur = ""
        for p in dir_parts:
            nxt = f"{cur}/{p}" if cur else p
            if cur not in dir_tree:
                dir_tree[cur] = {'subdirs': set(), 'files': []}
            dir_tree[cur]['subdirs'].add(p)
            cur = nxt
        if cur not in dir_tree:
            dir_tree[cur] = {'subdirs': set(), 'files': []}
        dir_tree[cur]['files'].append((fname, rel_path, idx))

    component_ids = []

    def render_dir(dir_rel, indent_level):
        indent = "  " * indent_level
        lines = []
        node = dir_tree.get(dir_rel, {'subdirs': set(), 'files': []})
        
        # Files in this directory
        for fname, full_rel, idx in sorted(node['files']):
            cid = f"CMP_Preset_{idx}_{sanitize_id(fname)}"
            fid = f"FIL_Preset_{idx}_{sanitize_id(fname)}"
            component_ids.append(cid)
            escaped_source = saxutils.escape(full_rel.replace('/', '\\'))
            escaped_name = saxutils.escape(fname)
            lines.append(f'{indent}<Component Id="{cid}" Guid="*" Win64="yes">')
            lines.append(f'{indent}  <File Id="{fid}" Name="{escaped_name}" Source="$(var.RepoRoot)\\{escaped_source}" KeyPath="yes" />')
            lines.append(f'{indent}</Component>')

        # Subdirectories
        for sub in sorted(node['subdirs']):
            subdir_rel = f"{dir_rel}/{sub}" if dir_rel else sub
            dir_id = f"DIR_{sanitize_id(subdir_rel)}"
            escaped_sub = saxutils.escape(sub)
            lines.append(f'{indent}<Directory Id="{dir_id}" Name="{escaped_sub}">')
            lines.extend(render_dir(subdir_rel, indent_level + 1))
            lines.append(f'{indent}</Directory>')

        return lines

    with open(OUTPUT_WXS, "w", encoding="utf-8") as out:
        out.write('<?xml version="1.0" encoding="UTF-8"?>\n')
        out.write('<Wix xmlns="http://schemas.microsoft.com/wix/2006/wi">\n')
        out.write('  <Fragment>\n')
        out.write('    <DirectoryRef Id="INSTALLFOLDER">\n')
        tree_lines = render_dir("", 3)
        out.write("\n".join(tree_lines) + "\n")
        out.write('    </DirectoryRef>\n\n')
        out.write('    <ComponentGroup Id="BundledPresetsGroup">\n')
        for cid in component_ids:
            out.write(f'      <ComponentRef Id="{cid}" />\n')
        out.write('    </ComponentGroup>\n')
        out.write('  </Fragment>\n')
        out.write('</Wix>\n')

    print(f"Generated {OUTPUT_WXS} successfully with {len(component_ids)} components.")

if __name__ == "__main__":
    main()
